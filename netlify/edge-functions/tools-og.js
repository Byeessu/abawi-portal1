// ─── Helpers ─────────────────────────────────────────────────────────────────

function slugify(str) {
  return String(str ?? '')
    .toLowerCase()
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

// Articles store `ti` sometimes JSON-encoded. Unwrap like ArticleDetail.jsx.
function unwrapTitle(raw) {
  let val = raw
  for (let i = 0; i < 4; i++) {
    if (typeof val !== 'string') return String(val ?? '')
    try {
      const p = JSON.parse(val)
      if (p && typeof p === 'object') val = p.ti ?? p.su ?? val
      else break
    } catch { break }
  }
  return String(val ?? '')
}

function slugToReadable(slug) {
  return String(slug ?? '')
    .split('-')
    .map(w => w ? w[0].toUpperCase() + w.slice(1) : '')
    .join(' ')
    .trim()
}

function esc(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}

// ─── Supabase helpers ─────────────────────────────────────────────────────────

// [context.production.environment] sets SUPABASE_URL/SUPABASE_ANON_KEY (runtime).
// VITE_ variants are build-time only → used as local-dev fallback.
function sbUrl()  { return Deno.env.get('SUPABASE_URL')  ?? Deno.env.get('VITE_SUPABASE_URL')  ?? '' }
function sbKey()  { return Deno.env.get('SUPABASE_ANON_KEY') ?? Deno.env.get('VITE_SUPABASE_ANON_KEY') ?? '' }
function sbHeaders() {
  const k = sbKey()
  return { apikey: k, Authorization: `Bearer ${k}` }
}

// Fetch article by slug (matches ArticleDetail.jsx slug logic).
async function fetchNewsMeta(slug) {
  const base = sbUrl()
  if (!base) return null
  try {
    const res = await fetch(
      `${base}/rest/v1/articles?select=ti,su,cover_url,tag&limit=600`,
      { headers: sbHeaders() }
    )
    if (!res.ok) return null
    const rows = await res.json()
    const found = rows.find(a => {
      const clean = unwrapTitle(a.ti)
      return slugify(clean) === slug || slugify(a.ti) === slug
    })
    if (!found) return null
    const title = unwrapTitle(found.ti).slice(0, 90)
    const tag   = found.tag || 'Actualité'
    const desc  = found.su
      ? String(found.su).replace(/<[^>]+>/g, '').slice(0, 200)
      : `${tag} · Actualités économiques et business pour l'Afrique — ABAWI`
    return {
      title: `${title} — ABAWI`,
      desc,
      image: found.cover_url || null,
      type:  'article',
    }
  } catch { return null }
}

// Fetch MaxAvis survey title + description.
async function fetchMaxAvisMeta(surveyId) {
  const base = sbUrl()
  if (!base) return null
  try {
    const res = await fetch(
      `${base}/rest/v1/maxavis_surveys?select=title,description&id=eq.${encodeURIComponent(surveyId)}&limit=1`,
      { headers: sbHeaders() }
    )
    if (!res.ok) return null
    const rows = await res.json()
    const row  = rows[0]
    if (!row) return null
    return {
      title: `${String(row.title).slice(0, 80)} — Sondage ABAWI`,
      desc:  row.description
        ? String(row.description).slice(0, 200)
        : 'Participez à ce sondage ABAWI et donnez votre avis en quelques clics.',
    }
  } catch { return null }
}

