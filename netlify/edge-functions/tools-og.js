// ─── Handler ──────────────────────────────────────────────────────────────────

export default async function handler(request, context) {
  const url  = new URL(request.url)
  const path = url.pathname

  let meta     = null
  let imageUrl = ROUTE_IMAGE[path] ?? null  // per-route banner; dynamic routes may override below
  let ogType   = 'website'

  // 1 — Exact static match
  meta = STATIC[path] ?? null

  // 2 — Dynamic route detection (only if no static match)
  if (!meta) {
    const newsM     = path.match(/^\/news\/(.+)$/)
    const packM     = path.match(/^\/digital\/pack\/(.+)$/)
    const guideM    = path.match(/^\/digital\/(?!pack\/)(.+)$/)
    const fascM     = path.match(/^\/academy\/(.+)$/)
    const podcastM  = path.match(/^\/podcasts\/(.+)$/)
    const storeM    = path.match(/^\/store\/(.+)$/)
    const santeM    = path.match(/^\/boutique-sante\/(.+)$/)
    const maxavisM  = path.match(/^\/maxavis\/(.+)$/)

    if (newsM) {
      const fetched = await fetchNewsMeta(newsM[1])
      if (fetched) {
        meta     = fetched
        imageUrl = fetched.image || '/og/news.webp'
        ogType   = fetched.type  || 'article'
      } else {
        meta = {
          title: `${slugToReadable(newsM[1])} — ABAWI Actualités`,
          desc:  'Actualité économique et business en Afrique de l\'Ouest — ABAWI, votre portail d\'information premium.',
        }
        ogType = 'article'
      }
    } else if (packM) {
      meta = resolvePackMeta(packM[1])
    } else if (guideM) {
      meta = resolveGuideMeta(guideM[1])
    } else if (fascM) {
      meta = resolveAcademyMeta(fascM[1])
    } else if (podcastM) {
      meta = resolvePodcastMeta(podcastM[1])
    } else if (storeM) {
      meta = resolveStoreMeta()
    } else if (santeM) {
      meta = resolveSanteMeta()
    } else if (maxavisM) {
      const fetched = await fetchMaxAvisMeta(maxavisM[1])
      meta = fetched ?? {
        title: 'Sondage ABAWI — Donnez votre avis',
        desc:  'Participez à ce sondage ABAWI et partagez votre opinion. Rapide, simple et anonyme.',
      }
    }
  }

  if (!meta) return context.next()

  const response = await context.next()
  if (!response.ok) return response

  let html = await response.text()

  const ogImg   = esc(imageUrl
    ? (imageUrl.startsWith('http') ? imageUrl : `${url.origin}${imageUrl}`)
    : `${url.origin}${OG_IMAGE_PNG}`)
  const titre   = esc(meta.title)
  const desc    = esc(String(meta.desc ?? '').slice(0, 200))
  const pageUrl = esc(`${url.origin}${url.pathname}`)

  html = html
    // Title & description
    .replace(/<title>[^<]*<\/title>/, `<title>${titre}</title>`)
    .replace(/<meta name="description"[^>]*>/, `<meta name="description" content="${desc}" />`)
    // Canonical URL
    .replace(/<link rel="canonical"[^>]*>/, `<link rel="canonical" href="${pageUrl}" />`)
    // OG tags
    .replace(/<meta property="og:title"[^>]*>/,       `<meta property="og:title" content="${titre}" />`)
    .replace(/<meta property="og:description"[^>]*>/, `<meta property="og:description" content="${desc}" />`)
    .replace(/<meta property="og:url"[^>]*>/,         `<meta property="og:url" content="${pageUrl}" />`)
    .replace(/<meta property="og:type"[^>]*>/,        `<meta property="og:type" content="${ogType}" />`)
    .replace(
      /<meta property="og:image"(?!:)[^>]*>/,
      `<meta property="og:image" content="${ogImg}" /><meta property="og:image:secure_url" content="${ogImg}" /><meta property="og:image:type" content="image/webp" />`
    )
    .replace(/<meta property="og:image:width"[^>]*>/,  `<meta property="og:image:width" content="1200" />`)
    .replace(/<meta property="og:image:height"[^>]*>/, `<meta property="og:image:height" content="630" />`)
    // Twitter / X
    .replace(/<meta name="twitter:title"[^>]*>/,       `<meta name="twitter:title" content="${titre}" />`)
    .replace(/<meta name="twitter:description"[^>]*>/, `<meta name="twitter:description" content="${desc}" />`)
    .replace(/<meta name="twitter:image"[^>]*>/,       `<meta name="twitter:image" content="${ogImg}" />`)

  return new Response(html, {
    status:  response.status,
    headers: {
      'content-type':  'text/html; charset=utf-8',
      'cache-control': 'no-cache, no-store',
    },
  })
}

